'use strict';
const assert = require('node:assert/strict');
const core = require('../personal-planner-core.js');
const hw = require('../homework-core.js');
const input = { title: 'Задачи 1–5', subject: 'Физика', date: '2026-11-06', minutes: 30, total: 5, completed: 2, status: 'doing', requiresSubmission: true };
const task = hw.makeTask(input);
assert.equal(hw.progress(task), 'doing');
assert.equal(hw.pendingSubmission(task), false);
const completed = hw.makeTask({ ...input, status: 'done' }, task);
assert.equal(completed.id, task.id);
assert.equal(completed.homework.completed, 5);
assert.equal(hw.pendingSubmission(completed), true, 'completion must not imply submission');
completed.homework.reportedSubmission = true;
completed.homework.reportedAt = 123;
const edited = hw.makeTask({ ...input, title: 'Уточнённое условие', status: 'done' }, completed);
assert.equal(edited.homework.reportedAt, 123, 'editing must preserve the manual submission claim');
assert.equal(hw.pendingSubmission(edited), false);
assert.equal(hw.list(core.normalizeData({ tasks: { [edited.id]: edited } }).tasks).length, 1, 'planner normalization and backups must preserve homework');
assert.equal(hw.progress({ ...completed, done: false }), 'todo', 'the shared planner completion flag is authoritative');
assert.equal(hw.safeUrl('javascript:alert(1)'), '');
assert.equal(hw.safeUrl('https://app.eschool.center.evil.test/'), '');
assert.equal(hw.safeUrl('https://user:password@app.eschool.center/'), '');
assert.equal(hw.safeUrl('https://app.eschool.center:444/'), '');
assert.ok(hw.safeUrl('https://app.eschool.center/Private/student/diary/1?d1=123'));
assert.throws(() => hw.makeTask({ ...input, date: '2026-02-30' }), /дату/);
assert.throws(() => hw.makeTask({ ...input, completed: 6 }), /количество/);
assert.throws(() => hw.makeTask({ ...input, minutes: 1.5 }), /время/);
assert.throws(() => hw.makeTask({ ...input, sourceUrl: 'https://unrelated.example/' }), /ссылку/);
const future = hw.makeTask({ ...input, title: 'Дальняя работа', date: '2026-12-10' });
const archive = hw.makeTask({ ...input, title: 'Архив' }); archive.homework.archived = true;
const tasks = Object.fromEntries([task, edited, future, archive].map(t => [t.id, t]));
// The edited record intentionally replaces the first one: one task, shared by both pages.
assert.equal(Object.keys(tasks).length, 3);
assert.equal(hw.filter(tasks, { view: 'now', query: 'далЬНЯЯ' }).length, 1);
assert.equal(hw.filter(tasks, { view: 'archive' })[0].title, 'Архив');
assert.equal(hw.filter(tasks, { view: 'send' }).length, 0);
const waiting = hw.makeTask({ ...input, status: 'done', title: 'Отправить' });
const recommendation = hw.recommendations([future, archive, waiting], '2026-11-04', 15);
assert.equal(recommendation[0].task.id, waiting.id);
assert.equal(recommendation.length, 2, 'archived work must not be recommended');
assert.match(recommendation[1].reason, /15 минут/);
assert.equal(hw.filter({ a: task }, { view: 'all', subject: 'Химия' }).length, 0);
console.log('homework: validation, shared state, submission claims and recommendations passed');
