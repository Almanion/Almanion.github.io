'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8');
const html = read('matcenter.html'), print = read('matcenter/75-print.js'), pdf = read('pdf-download.js');
assert.match(html, /id="mcPrintButton"[^>]*class="print-export-button"/);
assert.match(html, /frame-src blob:/, 'local PDFs must be allowed in the preview without widening remote access');
assert.match(print, /series\.tasks\.slice\(\)\.sort/, 'print all original rows, never just filtered cards');
assert.doesNotMatch(print, /task\.hint|task\.status|personalSolved|tasksContainer|fetch\(/, 'private handouts contain conditions only, with no new backend requests');
assert.match(print, /if \(token !== revision \|\| !authToken \|\| !isOpen\(\)\) return/);
assert.match(print, /URL\.revokeObjectURL/);
assert.match(read('matcenter/20-auth.js'), /MatcenterSeriesPrint\?\.reset/);
assert.match(pdf, /generateHandout/);
assert.match(pdf, /font:13\.333333px\/1\.15 AlmanionHandout,serif/);
assert.match(pdf, /margins: \[22\.68, 22\.68, 22\.68, 841\.89 \/ 2 \+ 22\.68\]/, 'reserve the lower half of every A4 page');
assert.match(pdf, /pageMargins: HANDOUT\.margins/);
assert.match(pdf, /height < HANDOUT\.height/);
assert.match(print, /A5 на ½ A4/);
assert.match(pdf, /font: 'CMUSerif'/);
assert.match(pdf, /numberText \?\? task\.number/);
assert.match(pdf, /if \(options\.heading\)/);
assert.match(pdf, /autoPrint: options\.autoPrint === true/);
assert.match(read('tools/site-files.json'), /"\.otf"/);
for (const file of ['cmunrm.otf', 'cmunbx.otf', 'cmunti.otf', 'cmunbi.otf', 'cm-unicode-OFL.txt']) assert.ok(fs.statSync(path.join(__dirname, '..', 'vendor/pdf', file)).size > 1000);
console.log('Matcenter private, source-faithful series printing: passed');
